import { join } from "node:path";
import { test, expect, clipName } from "./engine";

test("open clips show a temporary drop view, remove selected references, and group settings", async ({ page, engine }, info) => {
  await page.goto(`${engine.url}/#/library`);
  await page.getByRole("button", { name: "Open clips", exact: true }).click();
  const paths = page.getByRole("textbox", { name: "Clip file paths" });
  await paths.fill(join(engine.folder, clipName));
  await page.getByRole("button", { name: "Open files", exact: true }).click();
  const card = page.getByRole("option", { name: clipName, exact: true });
  await expect(card).toBeVisible();
  await page.evaluate(() => {
    const dataTransfer = new DataTransfer();
    dataTransfer.items.add(new File([""], "more.mcraw"));
    window.dispatchEvent(new DragEvent("dragenter", { bubbles: true, dataTransfer }));
  });
  const drop = page.getByRole("heading", { name: "Drop clips here", exact: true });
  await expect(drop).toBeVisible();
  await expect(card).toBeHidden();
  await page.screenshot({ path: info.outputPath("drop-view.png") });
  await page.evaluate(() => window.dispatchEvent(new DragEvent("dragleave")));
  await expect(drop).toHaveCount(0);
  await expect(card).toBeVisible();
  await page.evaluate(path => {
    const dataTransfer = new DataTransfer();
    dataTransfer.setData("text/uri-list", `file://${path}`);
    window.dispatchEvent(new DragEvent("dragenter", { dataTransfer }));
    // A drop on the app header is also accepted.
    document.querySelector("header")!.dispatchEvent(new DragEvent("drop", { bubbles: true, cancelable: true, dataTransfer }));
  }, join(engine.folder, clipName));
  await expect(drop).toHaveCount(0);
  await expect(card).toBeVisible();
  await card.getByRole("button", { name: `More actions for ${clipName}` }).click();
  await page.getByRole("menuitem", { name: "Remove from session" }).click();
  await expect(card).toHaveCount(0);
  await expect(drop).toBeVisible();
  expect((await (await page.request.get(`${engine.url}/api/v1/opened-clips`)).json()).clips).toEqual([]);
  await page.goto(`${engine.url}/#/settings`);
  await expect(page.getByRole("region", { name: "General", exact: true }).getByRole("textbox", { name: "Mount folder", exact: true })).toBeVisible();
  const system = page.getByRole("region", { name: "System", exact: true });
  await expect(system.getByRole("heading", { name: "File manager" })).toBeVisible();
  await expect(system.getByRole("heading", { name: "File association" })).toBeVisible();
  await expect(page.getByText("Restore sent media", { exact: true })).toHaveCount(0);
  const resolve = page.getByRole("region", { name: "DaVinci Resolve", exact: true });
  const free = resolve.getByRole("radio", { name: "Free", exact: true });
  const studio = resolve.getByRole("radio", { name: "Studio", exact: true });
  const combined = resolve.getByRole("radio", { name: "With the video" });
  const linked = resolve.getByRole("radio", { name: "Separate, kept linked" });
  const unlinked = resolve.getByRole("radio", { name: "Separate, unlinked" });
  const saved = async () => (await (await page.request.get(`${engine.url}/api/v1/settings`)).json());
  await expect(free).toBeChecked();
  await expect(combined).toBeChecked();
  await expect(resolve.getByText("Timelines larger than 3840 x 2160 are scaled down to fit.", { exact: false })).toBeVisible();
  await studio.check();
  await expect(resolve.getByText("Timelines keep the source resolution.")).toBeVisible();
  await linked.check();
  await expect.poll(async () => { const values = await saved(); return [values.resolve_full_resolution, values.resolve_separate_audio, values.resolve_link_audio]; }).toEqual([true, true, true]);
  await unlinked.check();
  await expect.poll(async () => (await saved()).resolve_link_audio).toBe(false);
  await page.reload();
  await expect(studio).toBeChecked();
  await expect(unlinked).toBeChecked();
  await page.screenshot({ path: info.outputPath("settings.png"), fullPage: true });
  await combined.check();
  await expect.poll(async () => { const values = await saved(); return [values.resolve_separate_audio, values.resolve_link_audio]; }).toEqual([false, false]);
  await page.reload();
  await expect(combined).toBeChecked();
  await page.screenshot({ path: info.outputPath("settings-combined.png"), fullPage: true });
});
