import { test, expect, addFolder, clipName, openSection } from "./engine";

test("Settings folder appears in Library and opens Resolve Settings", async ({ page, engine }) => {
  await addFolder(page, engine);
  const card = page.getByRole("option", { name: clipName, exact: true });
  await expect(card.getByText("RAW", { exact: true })).toBeVisible();
  const library = await (await page.request.get(`${engine.url}/api/v1/library`)).json();
  const seconds = Math.round(library.clips[0].duration_s);
  const clock = `${String(Math.floor(seconds / 60)).padStart(2, "0")}:${String(seconds % 60).padStart(2, "0")}`;
  await expect(card.locator(".duration")).toHaveText(clock);
  await card.click();
  await page.getByRole("tab", { name: "Resolve Settings", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Orientation", exact: true })).toBeVisible();
});

test("exchanges vignette JSON through the browser and keeps calibration visualisations on demand", async ({ page, engine }) => {
  await addFolder(page, engine);
  const card = page.getByRole("option", { name: clipName, exact: true });
  await card.click();
  const listing = await (await page.request.get(`${engine.url}/api/v1/library`)).json();
  const id = listing.clips[0].id;
  const base = `${engine.url}/api/v1/clips/${id}`;
  await card.getByRole("button", { name: `More actions for ${clipName}`, exact: true }).click();
  const downloading = page.waitForEvent("download");
  await page.getByRole("menuitem", { name: "Export Vignette Profile...", exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toContain("vignette.json");
  const panel = page.getByRole("region", { name: "Vignette profile", exact: true });
  await expect(panel).toContainText(`Source: ${clipName}`);
  await panel.getByRole("button", { name: "Close", exact: true }).click();
  const profile = await (await page.request.get(base + "/vignette-profile")).json();
  profile.gains = profile.gains.map((plane: number[]) => plane.map(() => 2));
  await card.getByRole("button", { name: `More actions for ${clipName}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Apply Vignette Profile to Selected...", exact: true }).click();
  await panel.getByLabel("Choose a profile JSON file (up to 2 MiB)").setInputFiles({ name: "profile.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(profile)) });
  await expect(panel).toContainText(`${clipName}: Applied`);
  const applied = await (await page.request.get(base + "/recipe")).json();
  expect(applied.resolved.develop.vignette_profile.gains[0][0]).toBe(2);
  await panel.getByRole("button", { name: "Close", exact: true }).click();
  await expect(page.getByRole("img", { name: "Lens shading R", exact: true })).toHaveCount(0);
  await page.getByRole("tab", { name: "Clip info", exact: true }).click();
  await openSection(page, /^Metadata/);
  await page.getByRole("complementary", { name: "Clip metadata" }).getByText("Calibration", { exact: true }).click();
  await expect(page.getByRole("img", { name: "Lens shading R", exact: true })).toBeVisible();
  await expect(page.getByRole("img", { name: "Recorded noise model", exact: true })).toBeVisible();
  await card.getByRole("button", { name: `More actions for ${clipName}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Clear Vignette Profile Override", exact: true }).click();
  await expect(panel).toContainText(`${clipName}: Override cleared`);
  expect((await (await page.request.get(base + "/recipe")).json()).resolved.develop.vignette_profile).toBeNull();
});

test("measures RAW diagnostics on demand and downloads exact JSON reports", async ({ page, engine }) => {
  const requests: string[] = [];
  page.on("request", request => { if (/\/(timing|raw-histogram)$/.test(request.url())) requests.push(request.url()); });
  await addFolder(page, engine);
  await page.getByRole("option", { name: clipName, exact: true }).click();
  await page.getByRole("tab", { name: "Clip info", exact: true }).click();
  await openSection(page, /^Metadata/);
  await page.getByRole("complementary", { name: "Clip metadata" }).getByText("RAW diagnostics", { exact: true }).click();
  expect(requests).toHaveLength(0);
  await page.getByRole("button", { name: "Read frame timing", exact: true }).click();
  await expect(page.getByRole("img", { name: "Recorded frame intervals", exact: true })).toBeVisible();
  const response = page.waitForResponse(response => response.url().endsWith("/raw-histogram"));
  await page.getByRole("button", { name: "Measure first RAW frame", exact: true }).click();
  const measured = await (await response).json();
  expect(measured.planes.reduce((sum: number, plane: { samples: number }) => sum + plane.samples, 0)).toBe(measured.width * measured.height);
  await expect(page.getByRole("img", { name: "First-frame RAW histogram", exact: true })).toBeVisible();
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "Save RAW histogram JSON", exact: true }).click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toBe(`${clipName}.raw-histogram.json`);
  const stream = await download.createReadStream();
  const chunks: Buffer[] = []; for await (const chunk of stream) chunks.push(Buffer.from(chunk));
  const saved = JSON.parse(Buffer.concat(chunks).toString("utf8"));
  expect(saved.planes).toEqual(measured.planes);
  expect(saved.timestamp_ns).toBe(measured.timestamp_ns);
  expect(requests).toHaveLength(2);
  await page.getByRole("tab", { name: "Clip info", exact: true }).click();
  await openSection(page, /^Metadata/);
  await page.getByRole("complementary", { name: "Clip metadata" }).getByText("Calibration", { exact: true }).click();
  await expect(page.getByRole("button", { name: "Copy calibration JSON", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Save calibration JSON", exact: true })).toBeVisible();
});
